import 'package:dio/dio.dart';
import 'package:flutter/foundation.dart';
import 'engine_types.dart';

/// Immutable domain value object bundling all parameters for an engine download execution request.
@immutable
class DownloadRequest {
  final String taskId;
  final String url;
  final String tempFilePath;
  final String localFilePath;
  final int knownFileSize;
  final bool supportsResume;
  final CancelToken cancelToken;
  final ValueChangedProgress onProgress;
  final int Function() speedLimitBytesPerSecond;
  final int Function() activeDownloadCount;
  final int threadCount;
  final String? customUserAgent;
  final String? referer;
  final String? cookies;
  final String? oauthToken;
  final List<Map<String, dynamic>>? Function()? getTorrentFiles;
  final int? torrentId;
  final bool isNameAutoGenerated;
  final List<String>? mirrorUrls;
  final bool adaptiveThreads;
  final int speedLimitKbps;
  final YtStreamKind? ytStreamKind;
  final int? ytCounterpartSize;
  final int? ytCounterpartDownloadedBytes;
  final bool isRetry;
  final int? metadataTimeoutSeconds;

  const DownloadRequest({
    required this.taskId,
    required this.url,
    required this.tempFilePath,
    required this.localFilePath,
    required this.knownFileSize,
    required this.supportsResume,
    required this.cancelToken,
    required this.onProgress,
    required this.speedLimitBytesPerSecond,
    required this.activeDownloadCount,
    this.threadCount = 0,
    this.customUserAgent,
    this.referer,
    this.cookies,
    this.oauthToken,
    this.getTorrentFiles,
    this.torrentId,
    this.isNameAutoGenerated = false,
    this.mirrorUrls,
    this.adaptiveThreads = false,
    this.speedLimitKbps = 0,
    this.ytStreamKind,
    this.ytCounterpartSize,
    this.ytCounterpartDownloadedBytes,
    this.isRetry = false,
    this.metadataTimeoutSeconds,
  });

  DownloadRequest copyWith({
    String? taskId,
    String? url,
    String? tempFilePath,
    String? localFilePath,
    int? knownFileSize,
    bool? supportsResume,
    CancelToken? cancelToken,
    ValueChangedProgress? onProgress,
    int Function()? speedLimitBytesPerSecond,
    int Function()? activeDownloadCount,
    int? threadCount,
    String? customUserAgent,
    String? referer,
    String? cookies,
    String? oauthToken,
    List<Map<String, dynamic>>? Function()? getTorrentFiles,
    int? torrentId,
    bool? isNameAutoGenerated,
    List<String>? mirrorUrls,
    bool? adaptiveThreads,
    int? speedLimitKbps,
    YtStreamKind? ytStreamKind,
    int? ytCounterpartSize,
    int? ytCounterpartDownloadedBytes,
    bool? isRetry,
    int? metadataTimeoutSeconds,
  }) {
    return DownloadRequest(
      taskId: taskId ?? this.taskId,
      url: url ?? this.url,
      tempFilePath: tempFilePath ?? this.tempFilePath,
      localFilePath: localFilePath ?? this.localFilePath,
      knownFileSize: knownFileSize ?? this.knownFileSize,
      supportsResume: supportsResume ?? this.supportsResume,
      cancelToken: cancelToken ?? this.cancelToken,
      onProgress: onProgress ?? this.onProgress,
      speedLimitBytesPerSecond:
          speedLimitBytesPerSecond ?? this.speedLimitBytesPerSecond,
      activeDownloadCount: activeDownloadCount ?? this.activeDownloadCount,
      threadCount: threadCount ?? this.threadCount,
      customUserAgent: customUserAgent ?? this.customUserAgent,
      referer: referer ?? this.referer,
      cookies: cookies ?? this.cookies,
      oauthToken: oauthToken ?? this.oauthToken,
      getTorrentFiles: getTorrentFiles ?? this.getTorrentFiles,
      torrentId: torrentId ?? this.torrentId,
      isNameAutoGenerated: isNameAutoGenerated ?? this.isNameAutoGenerated,
      mirrorUrls: mirrorUrls ?? this.mirrorUrls,
      adaptiveThreads: adaptiveThreads ?? this.adaptiveThreads,
      speedLimitKbps: speedLimitKbps ?? this.speedLimitKbps,
      ytStreamKind: ytStreamKind ?? this.ytStreamKind,
      ytCounterpartSize: ytCounterpartSize ?? this.ytCounterpartSize,
      ytCounterpartDownloadedBytes:
          ytCounterpartDownloadedBytes ?? this.ytCounterpartDownloadedBytes,
      isRetry: isRetry ?? this.isRetry,
      metadataTimeoutSeconds:
          metadataTimeoutSeconds ?? this.metadataTimeoutSeconds,
    );
  }
}

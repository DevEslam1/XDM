import 'package:dio/dio.dart';
import 'package:dmx/core/domain/engine_types.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  group('DownloadRequest', () {
    late CancelToken token;
    late DownloadProgress lastProgress;

    setUp(() {
      token = CancelToken();
      lastProgress = const DownloadProgress(
        downloadedBytes: 0,
        fileSize: 0,
        speed: 0,
        eta: null,
      );
    });

    DownloadRequest build({YtStreamKind? yt}) => DownloadRequest(
          taskId: 't1',
          url: 'https://example.com/a.zip',
          tempFilePath: '/tmp/a',
          localFilePath: '/dl/a',
          knownFileSize: 10,
          supportsResume: true,
          cancelToken: token,
          onProgress: (p) => lastProgress = p,
          speedLimitBytesPerSecond: () => 0,
          activeDownloadCount: () => 1,
          threadCount: 4,
          customUserAgent: 'ua',
          referer: 'ref',
          cookies: 'c',
          oauthToken: 'oauth',
          getTorrentFiles: () => null,
          torrentId: 5,
          isNameAutoGenerated: true,
          mirrorUrls: const ['m1'],
          adaptiveThreads: true,
          speedLimitKbps: 100,
          ytStreamKind: yt,
          ytCounterpartSize: 20,
          ytCounterpartDownloadedBytes: 5,
          isRetry: true,
          metadataTimeoutSeconds: 30,
        );

    test('constructor stores values and callbacks work', () {
      final r = build();
      expect(r.taskId, 't1');
      expect(r.threadCount, 4);
      expect(r.speedLimitKbps, 100);
      expect(r.isRetry, isTrue);
      expect(r.speedLimitBytesPerSecond(), 0);
      expect(r.activeDownloadCount(), 1);
      expect(r.getTorrentFiles!(), isNull);

      r.onProgress(lastProgress);
      expect(lastProgress.downloadedBytes, 0);
    });

    test('defaults', () {
      final r = DownloadRequest(
        taskId: 't',
        url: 'u',
        tempFilePath: 'tp',
        localFilePath: 'lp',
        knownFileSize: 0,
        supportsResume: false,
        cancelToken: token,
        onProgress: (_) {},
        speedLimitBytesPerSecond: () => 0,
        activeDownloadCount: () => 0,
      );
      expect(r.threadCount, 0);
      expect(r.adaptiveThreads, isFalse);
      expect(r.speedLimitKbps, 0);
      expect(r.isNameAutoGenerated, isFalse);
      expect(r.isRetry, isFalse);
      expect(r.metadataTimeoutSeconds, isNull);
      expect(r.customUserAgent, isNull);
    });

    test('copyWith overrides and preserves', () {
      final r = build(yt: YtStreamKind.video);
      final c = r.copyWith(
        taskId: 't2',
        url: 'u2',
        tempFilePath: 'tp2',
        localFilePath: 'lp2',
        knownFileSize: 99,
        supportsResume: false,
        threadCount: 8,
        customUserAgent: 'ua2',
        referer: 'r2',
        cookies: 'c2',
        oauthToken: 'o2',
        torrentId: 6,
        isNameAutoGenerated: false,
        mirrorUrls: const ['m2'],
        adaptiveThreads: false,
        speedLimitKbps: 0,
        ytStreamKind: YtStreamKind.audio,
        ytCounterpartSize: 1,
        ytCounterpartDownloadedBytes: 1,
        isRetry: false,
        metadataTimeoutSeconds: 60,
      );
      expect(c.taskId, 't2');
      expect(c.threadCount, 8);
      expect(c.ytStreamKind, YtStreamKind.audio);
      expect(c.metadataTimeoutSeconds, 60);

      final same = r.copyWith();
      expect(same.taskId, r.taskId);
      expect(same.url, r.url);
      expect(same.threadCount, r.threadCount);
    });
  });
}
